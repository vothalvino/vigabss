'use strict';
// A receipt, an invoice or a quote that fits on one page is one page. The
// "generated" line at the foot used to land on a page of its own.

const PDFDocument = require('pdfkit');
const { drawFooter } = require('../src/services/pdfService');

function build(draw) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'LETTER', margin: 50, bufferPages: true });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('error', reject);
    let pages;
    doc.on('end', () => resolve({ pages, bytes: Buffer.concat(chunks) }));
    draw(doc);
    // Counted before the document is closed: pages are still held then.
    pages = doc.bufferedPageRange().count;
    doc.end();
  });
}

const LINE = 'Generated by VigaBSS — 2026-11-26T06:00:00.000Z';

test('writing the footer the old way starts a second page (what this guards against)', async () => {
  const { pages } = await build((doc) => {
    doc.fontSize(20).text('Receipt', 50, 50);
    doc.fontSize(7).text(LINE, 50, 740, { align: 'center', width: doc.page.width - 100 });
  });
  expect(pages).toBe(2);
});

test('the footer stays on the page it belongs to, at both heights the documents use', async () => {
  for (const y of [740, 750]) {
    const { pages } = await build((doc) => {
      doc.fontSize(20).text('Receipt', 50, 50);
      drawFooter(doc, LINE, y);
    });
    expect([y, pages]).toEqual([y, 1]);
  }
});

test('a long legal footer that wraps still stays on the page', async () => {
  const { pages } = await build((doc) => drawFooter(doc, `${'Aviso legal de la empresa. '.repeat(12)}— ${LINE}`, 740));
  expect(pages).toBe(1);
});

test('the page keeps its bottom margin for whatever is written next', async () => {
  let before; let after;
  await build((doc) => {
    before = doc.page.margins.bottom;
    drawFooter(doc, LINE, 740);
    after = doc.page.margins.bottom;
  });
  expect(after).toBe(before);
  expect(before).toBe(50);
});

test('every document writes its footer through the helper', () => {
  const src = require('fs').readFileSync(require('path').join(__dirname, '..', 'src', 'services', 'pdfService.js'), 'utf8');
  expect(src.match(/^ +drawFooter\(doc, /gm).length).toBe(6);
  expect(src).not.toMatch(/\.text\([^\n]*PAGE_MARGIN, 7[45]0, \{ align: 'center'/);
});
